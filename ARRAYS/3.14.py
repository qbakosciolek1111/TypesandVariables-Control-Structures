# Creates a tuple containing a single word and prints the type of the variable
#
word_tuple = ('computation',)  # typ: tuple (krotka) z jednym elementem typu str; PRZECINEK po elemencie jest tu najważniejszy, bo to on tworzy krotkę, a nie nawiasy

print(word_tuple)  # print() to funkcja wbudowana; wypisze ('computation',)
print(type(word_tuple))  # type() to funkcja wbudowana; zwraca typ obiektu, a print() wypisuje go jako <class 'tuple'>